_KANA_RE = re.compile(r"[ぁ-ゖァ-ヺー]")

def romaji_to_hiragana(slug: str) -> str:
    """ローマ字スラッグを best-effort でひらがなに変換する(照合用)。変換不能部分は捨てる。
    既にかなの場合(モデルが id を日本語で出した場合)は敬称だけ落としてそのまま返す。
    ※かな入力を旧実装は空文字にしてしまい、mentioned_absent の照合(R504等)が
      全て誤FAILになるバグがあった(2026-07-21 パイロットで発覚・修正)。"""
    if _KANA_RE.search(slug):
        return re.sub(r"(さん|くん|ちゃん)$", "", slug.strip())
    s = slug.lower().split("_")[0]  # "usagi_red_hat" → "usagi"
    if s in _ROMAJI_OVERRIDES:
        return _ROMAJI_OVERRIDES[s]
    out, i = [], 0
    while i < len(s):
        # 促音: 同一子音の連続 (kk, tt, pp, ss...)
        if i + 1 < len(s) and s[i] == s[i + 1] and s[i] not in "aiueon":
            out.append("っ")
            i += 1
            continue
        # 撥音: n の後ろが子音 or 末尾
        if s[i] == "n" and (i + 1 >= len(s) or s[i + 1] not in "aiueoy"):
            out.append("ん")
            i += 1
            continue
        for rom, kana in _ROMAJI_TABLE:
            if s.startswith(rom, i):
                out.append(kana)
                i += len(rom)
                break
        else:
            i += 1  # 変換不能文字はスキップ
    return "".join(out)

# ---------------- 本文の文字種チェック用 (R501) ----------------

# ひらがな・カタカナ・長音・記号(読点句点・かぎかっこ・感嘆疑問・中点・空白改行)のみ許可
ALLOWED_TEXT_RE = re.compile(
    r"^[ぁ-ゖァ-ヺーーゝゞ、。「」『』！？!?・…〜～\s]*$"
)

def find_disallowed_chars(text: str) -> list[str]:
    """R501違反文字(漢字・英数字など)を列挙する。"""
    return sorted({ch for ch in text if not ALLOWED_TEXT_RE.match(ch)})

def tokenize_kana(text: str) -> list[str]:
    """分かち書き・句読点区切りでトークン化(季節語・NG語の先頭一致照合用)。"""
    return [t for t in re.split(r"[\s、。「」『』！？!?・…〜～]+", text) if t]

def count_chars(text: str) -> int:
    """文字数(スペース・改行・句読点等の記号を除いた かな文字数)。"""
    return len(re.sub(r"[\s、。「」『』！？!?・…〜～]", "", text))

